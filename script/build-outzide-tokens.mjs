// Board 39: OutZide runs in an iframe and can't see the site's tokens. This builds
// one token file for it from the design-system sources, so a token change reaches
// OutZide on the next deploy with no hand edit. Only variable files are carried;
// base, type and effect rules would restyle the iframe.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const SOURCES = ["colors.css", "rooms.css", "map.css", "chrome.css"];
const OUT = "client/public/outzide-map/assets/zaylist-tokens.css";
const HTML = "client/public/outzide-map/index.html";

export async function outzideTokens() {
  const parts = await Promise.all(SOURCES.map(async name =>
    `/* ${name} */\n${(await readFile(new URL(`client/src/components/ds/tokens/${name}`, root), "utf8")).trim()}\n`));
  const css = `/* Generated by script/build-outzide-tokens.mjs from client/src/components/ds/tokens. Do not edit. */\n${parts.join("\n")}`;
  const hash = createHash("sha256").update(css).digest("hex").slice(0, 10);
  const html = (await readFile(new URL(HTML, root), "utf8"))
    .replace(/assets\/zaylist-tokens\.css\?v=[0-9a-f]+/, `assets/zaylist-tokens.css?v=${hash}`);
  return { css, hash, html };
}

export async function writeOutzideTokens() {
  const { css, hash, html } = await outzideTokens();
  await writeFile(new URL(OUT, root), css);
  await writeFile(new URL(HTML, root), html);
  return hash;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`outzide tokens ${await writeOutzideTokens()}`);
}
